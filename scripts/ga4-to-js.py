#!/usr/bin/env python3
"""Turn GA4 CSV exports into ga4/ga4-data.js for the Traffic page.

The page can't read local CSV files by itself when opened from disk, but it can load a
.js file next to it. This script wraps your exports, unchanged, in that file. The page
parses them exactly as it parses files added by drag and drop.

    python3 scripts/ga4-to-js.py ~/Downloads/ga4-exports/*.csv
    python3 scripts/ga4-to-js.py ~/Downloads/ga4-exports/        # every .csv in a folder

Output: ga4/ga4-data.js (ignored by git; never commit it).

Recognised exports (by column names, not file names):
  - Views by day:    Date + Views [+ Active users] [+ Page path]
  - Views by hour:   Date + hour (YYYYMMDDHH) + Views [+ Page path]
  - Views by minute: dateHourMinute (Query Explorer) or "Date hour and minute" + Views
  - Sources:         Session source / medium [+ Page path] + Sessions
  - Channels:        Session primary channel group + Sessions
  - Pages:           Page path and screen class + Views

Standard library only.
"""
import csv
import io
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ga4" / "ga4-data.js"

KNOWN = [  # (label, any of these columns must be present) - mirrors the detection in index.html
    ("minute", {"Date hour and minute", "Date + hour + minute", "dateHourMinute"}),
    ("hourly", {"Date + hour (YYYYMMDDHH)", "dateHour"}),
    ("sources", {"Session source / medium", "sessionSourceMedium"}),
    ("channels", {"Session primary channel group (Default Channel Group)", "Session default channel group",
                  "sessionDefaultChannelGroup", "sessionPrimaryChannelGroup"}),
    ("daily", {"Date", "date"}),
    ("pages", {"Page path and screen class", "Page path", "pagePath"}),
]


def header_of(text):
    for line in text.splitlines():
        if line and not line.startswith("#"):
            return [h.strip() for h in next(csv.reader(io.StringIO(line)))]
    return []


def kind_of(header):
    lowered = {h.lower() for h in header}
    for label, cols in KNOWN:
        if any(c.lower() in lowered for c in cols):
            return label
    return None


def main(args):
    paths = []
    for a in args:
        p = Path(a).expanduser()
        paths += sorted(p.glob("*.csv")) if p.is_dir() else [p]
    if not paths:
        sys.exit(__doc__)
    exports = []
    for p in paths:
        text = p.read_text(encoding="utf-8-sig")
        kind = kind_of(header_of(text))
        if not kind:
            print(f"  skipped  {p.name}: not a recognised GA4 export")
            continue
        exports.append({"file": p.name, "text": text})
        print(f"  {kind:<8} {p.name}")
    if not exports:
        sys.exit("Nothing to write.")
    OUT.parent.mkdir(exist_ok=True)
    payload = {"generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "exports": exports}
    js = json.dumps(payload, ensure_ascii=False, indent=1).replace("</", "<\\/")
    OUT.write_text("// Local GA4 traffic data for the Traffic page. Generated by scripts/ga4-to-js.py.\n"
                   "// Aggregated counts only. Do not commit this file.\n"
                   f"window.GA4_DATA = {js};\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(exports)} exports)")


if __name__ == "__main__":
    main(sys.argv[1:])
